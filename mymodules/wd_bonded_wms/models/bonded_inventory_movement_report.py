# -*- coding: utf-8 -*-
import base64
import io

import xlsxwriter

from odoo import api, fields, models
from odoo.exceptions import ValidationError


REPORT_MUTATION_TYPE_SELECTION = [
    ('opening_balance', 'Opening Balance'),
    ('inbound', 'Inbound'),
    ('outbound', 'Outbound'),
    ('finding', 'Finding'),
    ('missing', 'Missing'),
    ('correction', 'Correction'),
    ('status_change', 'Status Change'),
    ('closing_balance', 'Closing Balance'),
]

REPORT_CUSTOMS_STATUS_SELECTION = [('bonded', 'Bonded'), ('free', 'Free')]


class BondedInventoryMovementReport(models.Model):
    _name = 'bonded.inventory.movement.report'
    _description = 'Inventory Movement History Report'
    _order = 'id desc'

    name = fields.Char(string='Report Name', required=True, default='New', copy=False, index=True)
    period_begin = fields.Date(string='Period Begin', required=True, copy=False, index=True)
    period_end = fields.Date(string='Period End', required=True, copy=False, index=True)
    warehouse_id = fields.Many2one('stock.warehouse', string='Warehouse', required=True, copy=False, index=True, default=lambda self: self.env.user.warehouse_id)
    customs_status_filter = fields.Selection([('all', 'Bonded & Non-Bonded'), ('bonded', 'Bonded'), ('free', 'Non-Bonded')], string='Customs Status', required=True, default='all', copy=False, index=True)
    state = fields.Selection([('draft', 'Draft'), ('done', 'Done')], string='State', required=True, default='draft', copy=False, index=True)
    generated_at = fields.Datetime(string='Generated At', readonly=True, copy=False, index=True)
    generated_by_id = fields.Many2one('res.users', string='Generated By', readonly=True, copy=False, index=True)
    opening_total_qty = fields.Float(string='Opening Total Qty', readonly=True, copy=False)
    inbound_total_qty = fields.Float(string='Inbound Total Qty', readonly=True, copy=False)
    outbound_total_qty = fields.Float(string='Outbound Total Qty', readonly=True, copy=False)
    finding_total_qty = fields.Float(string='Finding Total Qty', readonly=True, copy=False)
    missing_total_qty = fields.Float(string='Missing Total Qty', readonly=True, copy=False)
    correction_total_qty = fields.Float(string='Correction Total Qty', readonly=True, copy=False)
    closing_total_qty = fields.Float(string='Closing Total Qty', readonly=True, copy=False)
    total_gross_weight = fields.Float(string='Total Gross Weight (kg)', readonly=True, copy=False)
    total_net_weight = fields.Float(string='Total Net Weight (kg)', readonly=True, copy=False)
    movement_lines = fields.One2many('bonded.inventory.movement.report.line', 'report_id', string='Movement Lines', copy=False)

    def action_generate(self):
        report_line_model = self.env['bonded.inventory.movement.report.line']
        book_line_model = self.env['bonded.book.line'].sudo()
        for rec in self:
            if rec.state != 'draft':
                raise ValidationError('A generated report cannot be generated again. Create a new report instead.')
            if rec.period_begin > rec.period_end:
                raise ValidationError('Period Begin cannot be later than Period End.')
            book_lines = book_line_model.search([
                ('date', '<=', rec.period_end),
                ('bonded_stock_id.inbound_id.warehouse', '=', rec.warehouse_id.id),
            ], order='date asc, id asc')
            grouped_lines = {}
            for book_line in book_lines:
                key = (book_line.bonded_book_id.id, book_line.product_id.id, book_line.inbound_tracking_no)
                grouped_lines.setdefault(key, []).append(book_line)
            movement_vals = []
            sequence = 1
            for line_list in grouped_lines.values():
                opening_lines = [line for line in line_list if line.date < rec.period_begin and line.operation_type != 'snapshot']
                period_lines = [line for line in line_list if rec.period_begin <= line.date <= rec.period_end and line.operation_type != 'snapshot']
                closing_lines = [line for line in line_list if line.date <= rec.period_end and line.operation_type != 'snapshot']
                if not period_lines and not opening_lines:
                    continue
                opening_line = opening_lines[-1] if opening_lines else False
                closing_line = closing_lines[-1] if closing_lines else False
                opening_qty = opening_line.running_balance_qty if opening_line else 0.0
                closing_qty = closing_line.running_balance_qty if closing_line else 0.0
                source_line = closing_line or opening_line or period_lines[-1]
                stock = source_line.bonded_stock_id
                inbound = stock.inbound_id
                inbound_line = stock.inbound_line_id
                filing = inbound_line.bonded_product_id
                customs_line = inbound_line.customs_file_line_id
                product = source_line.product_id
                base_vals = {
                    'report_id': rec.id,
                    'source_book_line_id': source_line.id,
                    'bonded_stock_id': stock.id,
                    'product_name_sku': product.default_code or product.display_name or '',
                    'product_description': filing.product_description or product.display_name or '',
                    'marks_article_technical_description': ' / '.join(part for part in (filing.article_number, filing.technical_description) if part),
                    'commodity_code': filing.hs_code or customs_line.hs_code or '',
                    'unique_identifier_no': source_line.inbound_tracking_no,
                    'inbound_no': inbound.name or '',
                    'qty_of_colli': 0.0,
                    'kind_of_colli': 'Carton',
                    'value_euro': 0.0,
                    'gross_weight': 0.0,
                    'net_weight': 0.0,
                    'container_no': inbound.cntr_no or '',
                    'country_of_origin': customs_line.origin_country_id.name or '',
                }
                def build_line_values(book_line, mutation_type, mutation_qty, status, date_of_mutation, outbound_no='', corresponding_mrn='', reference=''):
                    line_vals = dict(base_vals)
                    line_vals.update({
                        'sequence': sequence,
                        'source_book_line_id': book_line.id,
                        'date': date_of_mutation,
                        'mutation_qty': mutation_qty,
                        'mutation_type': mutation_type,
                        'outbound_no': outbound_no,
                        'corresponding_mrn': corresponding_mrn,
                        'customs_status': 'free' if status == 'vrij' else 'bonded',
                        'qty_of_colli': mutation_qty,
                        'value_euro': mutation_qty * stock.unit_value,
                        'gross_weight': mutation_qty * inbound_line.gross_weight,
                        'net_weight': mutation_qty * inbound_line.net_weight,
                        'reference': reference,
                    })
                    return line_vals
                if opening_line and opening_qty:
                    status = opening_line.to_status or opening_line.from_status or 'entrepot'
                    line_vals = build_line_values(opening_line, 'opening_balance', opening_qty, status, rec.period_begin)
                    if rec.customs_status_filter == 'all' or line_vals['customs_status'] == rec.customs_status_filter:
                        movement_vals.append(line_vals)
                        sequence += 1
                for book_line in period_lines:
                    mutation_type = {
                        'bonded_inbound': 'inbound',
                        'customs_outbound': 'outbound',
                        't1_outbound': 'outbound',
                        'sample_check': 'finding',
                        'shortage': 'missing',
                        'destruction': 'correction',
                        'rto': 'outbound',
                        'status_change': 'status_change',
                    }.get(book_line.operation_type)
                    if not mutation_type:
                        continue
                    outbound = book_line.picking_id.bonded_outbound_id or book_line.customs_file_id.bonded_outbound_id
                    outbound_no = outbound.name if outbound else ''
                    mrn = book_line.customs_file_id.mrn or book_line.customs_file_id.mrn_id.mrn or ''
                    reference = outbound.reference if outbound else inbound.reference or ''
                    if mutation_type == 'status_change':
                        status_qty = stock.quantity
                        for status, mutation_qty in ((book_line.from_status, -status_qty), (book_line.to_status, status_qty)):
                            if not status:
                                continue
                            line_vals = build_line_values(book_line, mutation_type, mutation_qty, status, book_line.date)
                            if rec.customs_status_filter == 'all' or line_vals['customs_status'] == rec.customs_status_filter:
                                movement_vals.append(line_vals)
                                sequence += 1
                        continue
                    status = (book_line.from_status or book_line.to_status or 'entrepot') if mutation_type in ('outbound', 'finding', 'missing', 'correction') else (book_line.to_status or book_line.from_status or 'entrepot')
                    line_vals = build_line_values(book_line, mutation_type, book_line.qty_change, status, book_line.date, outbound_no, mrn, reference)
                    if rec.customs_status_filter == 'all' or line_vals['customs_status'] == rec.customs_status_filter:
                        movement_vals.append(line_vals)
                        sequence += 1
                if closing_line:
                    status = closing_line.to_status or closing_line.from_status or 'entrepot'
                    line_vals = build_line_values(closing_line, 'closing_balance', closing_qty, status, rec.period_end)
                    if rec.customs_status_filter == 'all' or line_vals['customs_status'] == rec.customs_status_filter:
                        movement_vals.append(line_vals)
                        sequence += 1
            if movement_vals:
                report_line_model.with_context(allow_inventory_movement_report_generation=True).create(movement_vals)
            totals = {key: 0.0 for key in ('opening_total_qty', 'inbound_total_qty', 'outbound_total_qty', 'finding_total_qty', 'missing_total_qty', 'correction_total_qty', 'closing_total_qty', 'total_gross_weight', 'total_net_weight')}
            for line_vals in movement_vals:
                mutation_type = line_vals['mutation_type']
                if mutation_type == 'opening_balance':
                    totals['opening_total_qty'] += line_vals['mutation_qty']
                elif mutation_type == 'inbound':
                    totals['inbound_total_qty'] += abs(line_vals['mutation_qty'])
                elif mutation_type == 'outbound':
                    totals['outbound_total_qty'] += abs(line_vals['mutation_qty'])
                elif mutation_type == 'finding':
                    totals['finding_total_qty'] += abs(line_vals['mutation_qty'])
                elif mutation_type == 'missing':
                    totals['missing_total_qty'] += abs(line_vals['mutation_qty'])
                elif mutation_type == 'correction':
                    totals['correction_total_qty'] += abs(line_vals['mutation_qty'])
                elif mutation_type == 'closing_balance':
                    totals['closing_total_qty'] += line_vals['mutation_qty']
                    totals['total_gross_weight'] += line_vals['gross_weight']
                    totals['total_net_weight'] += line_vals['net_weight']
            rec.write({
                'name': '%s-%s' % (fields.Date.to_string(rec.period_begin).replace('-', ''), fields.Date.to_string(rec.period_end).replace('-', '')),
                'state': 'done',
                'generated_at': fields.Datetime.now(),
                'generated_by_id': self.env.user.id,
                **totals,
            })
        return {'type': 'ir.actions.client', 'tag': 'reload'}

    def action_export_xlsx(self):
        attachment_model = self.env['ir.attachment']
        action = False
        for rec in self:
            if rec.state != 'done':
                raise ValidationError('Generate the report before exporting Excel.')
            output = io.BytesIO()
            workbook = xlsxwriter.Workbook(output, {'in_memory': True})
            worksheet = workbook.add_worksheet('Inventory Movement')
            label_format = workbook.add_format({'bold': True})
            number_format = workbook.add_format({'num_format': '0.00'})
            header_format = workbook.add_format({'bold': True, 'align': 'center', 'valign': 'vcenter', 'bg_color': '#F1F1F1', 'border': 1})
            cell_format = workbook.add_format({'border': 1, 'valign': 'vcenter'})
            line_number_format = workbook.add_format({'border': 1, 'valign': 'vcenter', 'align': 'right', 'num_format': '0.00'})
            generated_at = fields.Datetime.context_timestamp(rec, rec.generated_at).strftime('%Y-%m-%d %H:%M:%S') if rec.generated_at else ''
            filter_label = dict(self._fields['customs_status_filter'].selection).get(rec.customs_status_filter, '')
            left_info = [('Report Name', rec.name), ('Period Begin', fields.Date.to_string(rec.period_begin)), ('Period End', fields.Date.to_string(rec.period_end)), ('Warehouse', rec.warehouse_id.display_name), ('Customs Status', filter_label)]
            right_info = [('Generated At', generated_at), ('Generated By', rec.generated_by_id.name or ''), ('Opening Total Qty', rec.opening_total_qty), ('Inbound Total Qty', rec.inbound_total_qty), ('Outbound Total Qty', rec.outbound_total_qty), ('Finding Total Qty', rec.finding_total_qty), ('Missing Total Qty', rec.missing_total_qty), ('Correction Total Qty', rec.correction_total_qty), ('Closing Total Qty', rec.closing_total_qty), ('Total Gross Weight (kg)', rec.total_gross_weight), ('Total Net Weight (kg)', rec.total_net_weight)]
            for row, (label, value) in enumerate(left_info):
                worksheet.write(row, 0, label, label_format)
                worksheet.write(row, 1, value or '')
            for row, (label, value) in enumerate(right_info):
                worksheet.write(row, 2, label, label_format)
                if isinstance(value, (int, float)):
                    worksheet.write_number(row, 3, value, number_format)
                else:
                    worksheet.write(row, 3, value or '')
            headers = ['Product Name (SKU)', 'Product Description', 'Marks/Article No./Tech Desc.', 'Commodity Code', 'Date', 'Unique Identifier No.', 'Mutation Qty(Pcs)', 'Mutation Type', 'Inbound No.', 'Outbound No.', 'Corresponding MRN', 'Customs Status', 'Qty of Colli', 'Kind of Colli', 'Value (Euro)', 'Gross Weight (kg)', 'Net Weight (kg)', 'Container No', 'Reference', 'Country of Origin']
            worksheet.write_row(11, 0, headers, header_format)
            worksheet.freeze_panes(12, 0)
            widths = [28, 28, 34, 18, 14, 22, 16, 18, 20, 20, 22, 16, 14, 16, 16, 18, 18, 20, 20, 18]
            for column, width in enumerate(widths):
                worksheet.set_column(column, column, width)
            mutation_labels = dict(REPORT_MUTATION_TYPE_SELECTION)
            status_labels = dict(REPORT_CUSTOMS_STATUS_SELECTION)
            movement_lines = rec.movement_lines.sudo().sorted(key=lambda item: (item.sequence, item.id))
            for row, line in enumerate(movement_lines, start=12):
                values = [line.product_name_sku, line.product_description, line.marks_article_technical_description, line.commodity_code, fields.Date.to_string(line.date), line.unique_identifier_no, line.mutation_qty, mutation_labels.get(line.mutation_type, ''), line.inbound_no, line.outbound_no, line.corresponding_mrn, status_labels.get(line.customs_status, ''), line.qty_of_colli, line.kind_of_colli, line.value_euro, line.gross_weight, line.net_weight, line.container_no, line.reference, line.country_of_origin]
                for column, value in enumerate(values):
                    if column in (6, 12, 14, 15, 16):
                        worksheet.write_number(row, column, value or 0.0, line_number_format)
                    else:
                        worksheet.write(row, column, value or '', cell_format)
            if movement_lines:
                worksheet.autofilter(11, 0, 11 + len(movement_lines), len(headers) - 1)
            workbook.close()
            attachment = attachment_model.create({
                'name': 'Inventory_Movement_History_%s.xlsx' % rec.name,
                'type': 'binary',
                'datas': base64.b64encode(output.getvalue()),
                'res_model': rec._name,
                'res_id': rec.id,
                'mimetype': 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
            })
            action = {'type': 'ir.actions.act_url', 'url': '/web/content/%s?download=true' % attachment.id, 'target': 'self'}
        return action


class BondedInventoryMovementReportLine(models.Model):
    _name = 'bonded.inventory.movement.report.line'
    _description = 'Inventory Movement History Report Line'
    _order = 'id desc'

    report_id = fields.Many2one('bonded.inventory.movement.report', string='Report', required=True, readonly=True, copy=False, ondelete='cascade', index=True)
    sequence = fields.Integer(string='Sequence', required=True, readonly=True, copy=False, index=True)
    source_book_line_id = fields.Many2one('bonded.book.line', string='Source Ledger Line', readonly=True, copy=False, ondelete='set null', index=True)
    bonded_stock_id = fields.Many2one('bonded.stock', string='Bonded Stock', readonly=True, copy=False, ondelete='set null', index=True)
    product_name_sku = fields.Char(string='Product Name (SKU)', readonly=True, copy=False, index=True)
    product_description = fields.Char(string='Product Description', readonly=True, copy=False)
    marks_article_technical_description = fields.Text(string='Marks/Article No./Tech Desc.', readonly=True, copy=False)
    commodity_code = fields.Char(string='Commodity Code', readonly=True, copy=False, index=True)
    date = fields.Date(string='Date', required=True, readonly=True, copy=False, index=True)
    unique_identifier_no = fields.Char(string='Unique Identifier No.', required=True, readonly=True, copy=False, index=True)
    mutation_qty = fields.Float(string='Mutation Qty(Pcs)', readonly=True, copy=False)
    mutation_type = fields.Selection(REPORT_MUTATION_TYPE_SELECTION, string='Mutation Type', required=True, readonly=True, copy=False, index=True)
    inbound_no = fields.Char(string='Inbound No.', readonly=True, copy=False, index=True)
    outbound_no = fields.Char(string='Outbound No.', readonly=True, copy=False, index=True)
    corresponding_mrn = fields.Char(string='Corresponding MRN', readonly=True, copy=False, index=True)
    customs_status = fields.Selection(REPORT_CUSTOMS_STATUS_SELECTION, string='Customs Status', required=True, readonly=True, copy=False, index=True)
    qty_of_colli = fields.Float(string='Qty of Colli', readonly=True, copy=False)
    kind_of_colli = fields.Char(string='Kind of Colli', readonly=True, copy=False)
    value_euro = fields.Float(string='Value (Euro)', readonly=True, copy=False)
    gross_weight = fields.Float(string='Gross Weight (kg)', readonly=True, copy=False)
    net_weight = fields.Float(string='Net Weight (kg)', readonly=True, copy=False)
    container_no = fields.Char(string='Container No', readonly=True, copy=False, index=True)
    reference = fields.Char(string='Reference', readonly=True, copy=False, index=True)
    country_of_origin = fields.Char(string='Country of Origin', readonly=True, copy=False)

    @api.model_create_multi
    def create(self, vals_list):
        if not self.env.context.get('allow_inventory_movement_report_generation'):
            raise ValidationError('Report lines can only be generated from the report.')
        return super().create(vals_list)
